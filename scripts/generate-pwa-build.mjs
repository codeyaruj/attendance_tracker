import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { extname, relative } from "node:path";

const ROOT = new URL("../", import.meta.url);
const TEMPLATE = new URL("../pwa/sw-template.js", import.meta.url);
const WORKER = new URL("../public/sw.js", import.meta.url);
const MANIFEST = new URL("../public/version.json", import.meta.url);
const CLIENT_INFO = new URL("../lib/pwa/build-info.ts", import.meta.url);
const HASHED_DIRECTORIES = [
  "app",
  "components",
  "db",
  "functions",
  "hooks",
  "lib",
  "pwa",
  "public/icons",
  "styles",
];
const HASHED_ROOT_FILES = [
  "next.config.ts",
  "package.json",
  "pnpm-lock.yaml",
  "postcss.config.mjs",
  "public/_headers",
  "tsconfig.json",
];
const HASHED_EXTENSIONS = new Set([
  ".css",
  ".js",
  ".json",
  ".mjs",
  ".png",
  ".svg",
  ".ts",
  ".tsx",
  ".webmanifest",
]);
const GENERATED_SOURCE_PATHS = new Set(["lib/pwa/build-info.ts"]);

function cleanBuildId(value) {
  const cleaned = value
    ?.trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]/g, "-");
  return cleaned ? cleaned.slice(0, 32) : undefined;
}

function gitValue(args) {
  try {
    return execFileSync("git", args, {
      cwd: ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return undefined;
  }
}

async function collectFiles(directory, result) {
  let entries;
  try {
    entries = await readdir(new URL(`${directory}/`, ROOT), {
      withFileTypes: true,
    });
  } catch {
    return;
  }
  for (const entry of entries) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) await collectFiles(path, result);
    else if (
      HASHED_EXTENSIONS.has(extname(entry.name)) &&
      !GENERATED_SOURCE_PATHS.has(path)
    )
      result.push(path);
  }
}

export async function deterministicSourceBuildId() {
  const paths = [...HASHED_ROOT_FILES];
  for (const directory of HASHED_DIRECTORIES) {
    await collectFiles(directory, paths);
  }
  const hash = createHash("sha256");
  for (const path of paths.sort()) {
    try {
      hash.update(
        relative(new URL(".", ROOT).pathname, new URL(path, ROOT).pathname),
      );
      hash.update("\0");
      hash.update(await readFile(new URL(path, ROOT)));
      hash.update("\0");
    } catch {
      // Optional source paths may not exist in every checkout.
    }
  }
  return `source-${hash.digest("hex").slice(0, 20)}`;
}

export async function resolveBuildId(environment = process.env) {
  for (const name of [
    "CF_PAGES_COMMIT_SHA",
    "GITHUB_SHA",
    "CI_COMMIT_SHA",
    "COMMIT_SHA",
  ]) {
    const value = cleanBuildId(environment[name]);
    if (value) return value;
  }
  const gitSha = cleanBuildId(gitValue(["rev-parse", "HEAD"]));
  return gitSha ?? deterministicSourceBuildId();
}

function resolveBuiltAt(environment = process.env) {
  const epoch = Number(environment.SOURCE_DATE_EPOCH);
  if (Number.isFinite(epoch) && epoch > 0) {
    return new Date(epoch * 1000).toISOString();
  }
  const commitDate = gitValue(["log", "-1", "--format=%cI"]);
  const parsed = commitDate ? new Date(commitDate) : undefined;
  return parsed && !Number.isNaN(parsed.valueOf())
    ? parsed.toISOString()
    : new Date().toISOString();
}

export async function generatePwaBuild(environment = process.env) {
  const buildId = await resolveBuildId(environment);
  const builtAt = resolveBuiltAt(environment);
  const template = await readFile(TEMPLATE, "utf8");
  if (!template.includes("__ATTENDSAFE_BUILD_ID__")) {
    throw new Error(
      "Service-worker template is missing its build-ID placeholder",
    );
  }
  const worker = template.replaceAll("__ATTENDSAFE_BUILD_ID__", buildId);
  const manifest = `${JSON.stringify({ buildId, builtAt }, null, 2)}\n`;
  const clientInfo = `// Generated by scripts/generate-pwa-build.mjs. Do not edit.\nexport const CURRENT_BUILD = {\n  buildId: ${JSON.stringify(buildId)},\n  builtAt: ${JSON.stringify(builtAt)},\n} as const;\nexport const CURRENT_BUILD_ID = CURRENT_BUILD.buildId;\n`;
  await Promise.all([
    writeFile(WORKER, worker),
    writeFile(MANIFEST, manifest),
    writeFile(CLIENT_INFO, clientInfo),
  ]);
  return { buildId, builtAt };
}

if (
  process.argv[1] &&
  import.meta.url === new URL(process.argv[1], "file:").href
) {
  const result = await generatePwaBuild();
  process.stdout.write(`Generated PWA build ${result.buildId}\n`);
}
